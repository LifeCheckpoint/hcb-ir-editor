/**
 * 从 lucide-static 生成 src/icons.js。
 * 只保留界面用到的图标，输出为「名称 -> svg 内部标记」的映射。
 * 用法：npm run icons
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const NAMES = [
  // 原语 · 流程
  'play',
  'pause',
  'square',
  'tag',
  'arrow-right-to-line',
  'layout-grid',
  'trophy',
  // 原语 · 台词
  'message-square-text',
  'user-round',
  'panel-bottom',
  'list-checks',
  // 原语 · 画面
  'mountain',
  'image',
  'image-plus',
  'download',
  'sun',
  'moon',
  'clapperboard',
  'film',
  'wand-sparkles',
  // 原语 · 立绘
  'person-standing',
  'eraser',
  'log-out',
  'move',
  'palette',
  'activity',
  // 原语 · 声音
  'music',
  'volume-2',
  'volume-x',
  'files',
  // 原语 · 演出
  'clock',
  'vibrate',
  'move-3d',
  'camera',
  'snowflake',
  'cloud-fog',
  'flag',
  // 原语 · 变量 / 备注
  'variable',
  'git-branch',
  'sticky-note',
  // 原语 · 扩展
  'terminal',
  // 界面
  'grip-vertical',
  'plus',
  'search',
  'book-open',
  'copy',
  'trash-2',
  'chevron-down',
  'chevron-right',
  'x',
  'info',
  'ellipsis',
  'eye',
  'check',
  'pencil',
  'files',
  'mic',
  'alert-triangle',
  'link',
  'history',
  'folder',
];

const dir = path.join(process.cwd(), 'node_modules', 'lucide-static', 'icons');
const entries = [];

for (const name of NAMES) {
  const raw = await readFile(path.join(dir, `${name}.svg`), 'utf8');
  const match = raw.replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!match) throw new Error(`无法解析图标 ${name}`);
  const inner = match[1].trim().replace(/>\s+</g, '><');
  entries.push([name, inner]);
}

const body = entries.map(([name, inner]) => `  '${name}':\n    '${inner.replace(/'/g, "\\'")}',`).join('\n');

const out = `/* 图标来自 Lucide — https://lucide.dev — ISC License。
   generated by tools/build-icons.mjs, 不要手改。 */
window.LUCIDE = {
${body}
};
`;

await writeFile(path.join(process.cwd(), 'src', 'icons.js'), out, 'utf8');
console.log(`wrote src/icons.js (${entries.length} icons)`);
